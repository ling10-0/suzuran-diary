function getCurrentCaseNumber() {
  const issue = document.querySelector('.gazette-case-head .gazette-issue b');
  if (issue) {
    const match = issue.textContent.match(/(\d+)/);
    if (match) return Number(match[1]);
  }

  const pager = document.querySelector('.case-pager span');
  if (pager) {
    const match = pager.textContent.match(/第\s*(\d+)/);
    if (match) return Number(match[1]);
  }

  return null;
}

function applyRevisedTravelCopy() {
  const caseNumber = getCurrentCaseNumber();
  const copy = revisedTravelByCaseNumber[caseNumber];
  const panel = document.querySelector('.document-copy.travel');
  if (!copy || !panel) return;

  const current = [...panel.querySelectorAll(':scope > p')].map(node => node.textContent.trim());
  if (current.length === copy.length && current.every((text, index) => text === copy[index])) return;

  panel.querySelectorAll(':scope > p').forEach(node => node.remove());
  const image = panel.querySelector('.travel-document-image');

  copy.forEach(text => {
    const paragraph = document.createElement('p');
    paragraph.textContent = text;
    panel.insertBefore(paragraph, image || null);
  });
}

const observer = new MutationObserver(applyRevisedTravelCopy);
observer.observe(document.documentElement, {childList: true, subtree: true});

document.addEventListener('click', () => window.setTimeout(applyRevisedTravelCopy, 0));
window.addEventListener('popstate', applyRevisedTravelCopy);
window.addEventListener('hashchange', applyRevisedTravelCopy);
applyRevisedTravelCopy();
